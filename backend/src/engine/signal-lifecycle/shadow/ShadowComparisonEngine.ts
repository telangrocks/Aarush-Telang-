import {
  CanonicalTradeSignal,
  OpportunityRecord,
  ShadowComparisonResult,
  ShadowClassification,
} from '../types/SignalLifecycleTypes';

/**
 * ShadowComparisonEngine
 *
 * Compares authoritative legacy alert pipeline outcomes against Stage A shadow
 * CanonicalTradeSignal outputs to classify discrepancies and measure parity.
 */
export class ShadowComparisonEngine {
  public static compare(
    symbol: string,
    legacySignal: any | null,
    shadowSignal: CanonicalTradeSignal | null,
    activeOpportunity?: OpportunityRecord | null,
    context?: {
      isLegacySuppressedByGate?: boolean;
      suppressionGate?: string;
    }
  ): ShadowComparisonResult {
    const timestamp = Date.now();
    const discrepancyReasons: string[] = [];
    const telemetry: Record<string, any> = {
      hasLegacy: !!legacySignal,
      hasShadow: !!shadowSignal,
      symbol,
    };

    // Case 1: Both produced nothing (no signal on both sides)
    if (!legacySignal && !shadowSignal) {
      return {
        symbol,
        timestamp,
        legacySignal: null,
        shadowSignal: null,
        classification: 'MATCH',
        discrepancyReasons: [],
        telemetry: { ...telemetry, detail: 'BOTH_NO_SIGNAL' },
      };
    }

    const legacyAction = (legacySignal?.side ?? legacySignal?.action ?? legacySignal?.type ?? '').toUpperCase();
    const shadowAction = shadowSignal?.action ? shadowSignal.action.toUpperCase() : null;

    telemetry.legacyAction = legacyAction || null;
    telemetry.shadowAction = shadowAction;

    // Case 2: Both produced signals
    if (legacySignal && shadowSignal) {
      if (legacyAction === shadowAction) {
        // Full match on direction!
        return {
          symbol,
          timestamp,
          legacySignal,
          shadowSignal,
          classification: 'MATCH',
          discrepancyReasons: [],
          telemetry: {
            ...telemetry,
            detail: 'DIRECTION_AND_ACTION_MATCH',
            legacyTimeframe: legacySignal.timeframe,
            shadowTimeframe: shadowSignal.timeframe,
            correlationScore: shadowSignal.correlationScore,
          },
        };
      } else {
        // Direction mismatch
        discrepancyReasons.push(`Direction mismatch: legacy=${legacyAction}, shadow=${shadowAction}`);
        return {
          symbol,
          timestamp,
          legacySignal,
          shadowSignal,
          classification: 'POTENTIAL_REGRESSION',
          discrepancyReasons,
          telemetry: {
            ...telemetry,
            detail: 'DIRECTION_CONFLICT',
          },
        };
      }
    }

    // Case 3: Shadow produced signal, legacy produced none
    if (!legacySignal && shadowSignal) {
      // Check if legacy was suppressed by Level 1 deduplication gate or reversal lock
      if (context?.isLegacySuppressedByGate) {
        discrepancyReasons.push(`Legacy suppressed by gate '${context.suppressionGate}', shadow resolved cleanly`);
        return {
          symbol,
          timestamp,
          legacySignal: null,
          shadowSignal,
          classification: 'EXPECTED_IMPROVEMENT',
          discrepancyReasons,
          telemetry: {
            ...telemetry,
            detail: 'LEGACY_SUPPRESSED_BY_GATE',
            gate: context.suppressionGate,
          },
        };
      }

      // Check if this is an existing opportunity consolidating across timeframes
      if (activeOpportunity && activeOpportunity.state === 'ACTIVE') {
        discrepancyReasons.push('Shadow consolidated cross-timeframe signal into active opportunity');
        return {
          symbol,
          timestamp,
          legacySignal: null,
          shadowSignal,
          classification: 'EXPECTED_IMPROVEMENT',
          discrepancyReasons,
          telemetry: {
            ...telemetry,
            detail: 'CROSS_TIMEFRAME_CONSOLIDATION',
            oppId: activeOpportunity.oppId,
          },
        };
      }

      // If active opportunity was superseded (reversal)
      if (activeOpportunity?.supersededBy) {
        discrepancyReasons.push('Shadow processed genuine directional reversal superseding prior opportunity');
        return {
          symbol,
          timestamp,
          legacySignal: null,
          shadowSignal,
          classification: 'EXPECTED_IMPROVEMENT',
          discrepancyReasons,
          telemetry: {
            ...telemetry,
            detail: 'REVERSAL_SUPERSEDED_PRIOR_OPP',
          },
        };
      }

      // Unexplained signal generated by shadow
      discrepancyReasons.push('Shadow generated canonical signal where legacy had no signal');
      return {
        symbol,
        timestamp,
        legacySignal: null,
        shadowSignal,
        classification: 'EXPECTED_IMPROVEMENT',
        discrepancyReasons,
        telemetry: {
          ...telemetry,
          detail: 'SHADOW_ONLY_SIGNAL',
        },
      };
    }

    // Case 4: Legacy produced signal, shadow produced none
    if (legacySignal && !shadowSignal) {
      discrepancyReasons.push(`Legacy produced ${legacyAction} alert, but shadow emitted no canonical signal`);
      return {
        symbol,
        timestamp,
        legacySignal,
        shadowSignal: null,
        classification: 'POTENTIAL_REGRESSION',
        discrepancyReasons,
        telemetry: {
          ...telemetry,
          detail: 'LEGACY_ALERT_MISSED_BY_SHADOW',
        },
      };
    }

    // Fallback
    return {
      symbol,
      timestamp,
      legacySignal,
      shadowSignal,
      classification: 'MATCH',
      discrepancyReasons,
      telemetry,
    };
  }
}
